"""Give every street a parody name (owner decision 2026-11-15): a sound-alike of the real name that is not itself
a real street here; if no good sound-alike exists, a random name from the word bank.

usage: make_street_names.py <osm tiles dir> [more tile dirs...] <out json>
Keeps the direction (North/South/...) and the type (Street/Avenue/...). Numbered streets ("15th Street") and route
numbers (Interstate 75, US 24) keep their numbers. Hand edits in the output file are preserved on re-runs
(entries marked "fixed": true, or any entry whose value differs from what this script would generate is left alone
only if listed under "_fixed")."""
import json, glob, os, re, sys, difflib, hashlib

dirs, OUT = sys.argv[1:-1], sys.argv[-1]
BANK = open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "source_data", "name_bank.txt")).read().split()

DIRS = ("North", "South", "East", "West", "Northeast", "Northwest", "Southeast", "Southwest")
TYPES = ("Street", "Avenue", "Road", "Drive", "Lane", "Court", "Place", "Boulevard", "Parkway", "Trail", "Way", "Circle",
         "Highway", "Pike", "Terrace", "Expressway", "Freeway", "Square", "Plaza", "Alley", "Path", "Run", "Row", "Crossing",
         "Pointe", "Point", "Loop", "Bend", "Cove", "Commons", "Walk", "Glen", "Green", "Trace", "Ridge", "Heights")
GENERIC = {"park", "creek", "hill", "hills", "ridge", "wood", "woods", "lake", "river", "valley", "view", "grove", "glen",
           "meadow", "meadows", "brook", "spring", "springs", "field", "fields", "farm", "farms", "oak", "oaks", "pine",
           "pines", "village", "estates", "garden", "gardens", "manor", "point", "pointe", "harbor", "bay", "shore",
           "old", "new", "saint", "st", "mount", "mt", "fort", "lower", "upper", "the", "of", "and", "de", "la", "le",
           "service", "access", "ramp", "exit", "entrance", "frontage", "jr", "dr", "martin", "luther", "king"}

names = set()
for d in dirs:
    for f in glob.glob(os.path.join(d, "*.json")):
        for e in json.load(open(f))["elements"]:
            t = e.get("tags", {})
            if e["type"] == "way" and "highway" in t and t.get("name"):
                names.add(t["name"].strip())

def split(n):
    w = n.split()
    pre = []; post = []
    while w and w[0] in DIRS: pre.append(w.pop(0))
    while w and w[-1] in DIRS: post.insert(0, w.pop())
    typ = []
    while w and w[-1] in TYPES and len(w) > 1: typ.insert(0, w.pop())
    return pre, " ".join(w), typ, post

real_bases = set()
for n in names:
    real_bases.add(split(n)[1].lower())

def h(s):
    return int(hashlib.md5(s.encode()).hexdigest()[:8], 16)

used = {}
def parody_word(word, key):
    """Sound-alike from the bank: same first letter preferred, high similarity, not a real street word."""
    wl = word.lower()
    best, score = None, 0.0
    for b in BANK:
        bl = b.lower()
        if bl == wl or bl in real_bases: continue
        r = difflib.SequenceMatcher(None, wl, bl).ratio()
        if bl[0] == wl[0]: r += 0.15
        if bl[-2:] == wl[-2:]: r += 0.1
        r -= 0.04 * used.get(b, 0)          # spread the bank around
        r += (h(key + b) % 100) / 5000.0    # deterministic tie-break
        if r > score: best, score = b, r
    if best is None or score < 0.62:
        # no convincing sound-alike: something random (deterministic per street)
        pool = [b for b in BANK if b.lower() not in real_bases]
        best = pool[h(key) % len(pool)]
    used[best] = used.get(best, 0) + 1
    return best

base_map = {}
def parody_base(base):
    if base in base_map: return base_map[base]
    if not base or re.search(r"\d", base):               # numbered streets and routes keep their numbers
        base_map[base] = base; return base
    words = base.split()
    # replace the most distinctive word (longest non-generic); keep the rest so the street keeps its feel
    cand = [i for i, w in enumerate(words) if w.lower().strip(".'") not in GENERIC and len(w) > 2]
    if not cand: cand = list(range(len(words)))
    i = max(cand, key=lambda k: (len(words[k]), -k))
    new = list(words)
    new[i] = parody_word(words[i].strip(".'"), base)
    out = " ".join(new)
    if out.lower() in real_bases:                          # still collides with a real street: go random
        new[i] = BANK[h(base + "x") % len(BANK)]; out = " ".join(new)
    base_map[base] = out
    return out

old = json.load(open(OUT)) if os.path.exists(OUT) else {}
fixed = old.get("_fixed", {})
result = {"_doc": "Street name parodies. Generated by tools/pipeline/make_street_names.py; put hand-picked names in _fixed (they win).",
          "_fixed": fixed}
for n in sorted(names):
    if n in fixed: result[n] = fixed[n]; continue
    pre, base, typ, post = split(n)
    result[n] = " ".join(pre + [parody_base(base)] + typ + post).strip()
json.dump(result, open(OUT, "w"), indent=0, ensure_ascii=False)
same = sum(1 for n in names if result[n] == n)
print(f"{len(names)} street names, {len(set(base_map))} distinct bases, {same} unchanged (numbered/routes)")
